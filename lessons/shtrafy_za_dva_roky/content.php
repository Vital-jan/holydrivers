<section class="section">
  <p>
    Часто мені ставлять питання: «Як не нахапатись штрафів за 2 роки після
    отримання посвідчення?»
  </p>

  <p>Відповім. Передусім відповідь очікувана — не порушуйте 🙂</p>

  <p>
    ПДР створені не для штрафів, а для нашої з вами безпеки. Якби більшість
    водіїв дотримувались правил, на дорогах було б комфортніше та безпечніше.
  </p>

  <p>
    Натомість в Україні чомусь існує дивна манера їзди — їхати настільки швидко,
    щоб усіх обігнати. Для чого? Простий експеримент доводить, що швидкість,
    особливо в місті, майже не дає виграшу в часі.
  </p>

  <p>
    Прокладіть маршрут у навігаторі та переконайтесь: зазначений час прибуття
    майже не зміниться від того, як часто ви змінюєте смугу руху або намагаєтесь
    їхати швидше за потік.
  </p>

  <h2 class="section-title">Найпоширеніші порушення у перші два роки</h2>

  <p>
    Ось порушення, через які можна легко потрапити на перездачу протягом перших
    двох років після отримання посвідчення:
  </p>

  <ul>
    <li>Автофіксація перевищення швидкості камерами контролю.</li>
    <li>Порушення правил зупинки та паркування.</li>
    <li>Проїзд смугою громадського транспорту.</li>
  </ul>

  <h2 class="section-title">Як уникнути штрафів за перевищення швидкості</h2>

  <p>
    Розташування камер контролю швидкості не є секретною інформацією. На сайті
    МВС є мапа з їх розташуванням, а навігатор Waze попереджає про наближення до
    камери.
  </p>

  <p>
    Штраф накладається за перевищення швидкості більше ніж на 20 км/год. Але
    дозволеною швидкістю залишається та, що зазначена в ПДР і на дорожніх
    знаках, без жодних «плюс 20».
  </p>

  <p>
    У разі ДТП вашу швидкість можуть визначити за записами камер, яких зараз
    багато на дорогах, біля будинків, магазинів і перехресть. Тому орієнтуватися
    лише на межу штрафу — погана ідея.
  </p>

  <p>
    Слідкуйте за дорожніми знаками, що обмежують швидкість. За межами міста
    особливо уважно дивіться на знаки початку та закінчення населеного пункту.
  </p>

  <p>
    Обираючи безпечну швидкість, водій має керуватися не лише обмеженнями, а й
    здоровим глуздом: якістю дорожнього покриття, напрямком дороги, оглядовістю,
    освітленням, погодними умовами та реальною дорожньою обстановкою.
  </p>

  <h2 class="section-title">Паркування без штрафів</h2>

  <p>
    Паркування у великому місті — серйозна проблема. Тому, плануючи поїздку,
    особливо в центр Києва, завчасно враховуйте, чи буде можливість
    припаркуватися без порушень.
  </p>

  <p>
    Іноді простіше відмовитись від поїздки на авто й скористатися громадським
    транспортом. Повернути автомобіль після евакуації нескладно, але неприємно
    та недешево.
  </p>

  <p>Обираючи місце для паркування, пам’ятайте про базові відстані:</p>

  <ul>
    <li>не менше 10 м від пішохідних переходів;</li>
    <li>не менше 10 м від перехресть;</li>
    <li>не менше 10 м від виїздів із прилеглих територій;</li>
    <li>не менше 30 м від зупинок громадського транспорту;</li>
    <li>на тротуарі має залишатися щонайменше 2 м для проходу пішоходів;</li>
    <li>
      на дорозі має залишатися щонайменше 3 м для проїзду іншого транспорту.
    </li>
  </ul>

  <p>
    Також звертайте увагу на жовту розмітку, яка забороняє зупинку або
    паркування. А несплачене паркування теж може призвести до штрафу.
  </p>

  <p>
    Паркування на смузі громадського транспорту — це вже, як то кажуть, премія
    Дарвіна 🙂
  </p>

  <h2 class="section-title">
    Чому не варто їхати смугою громадського транспорту
  </h2>

  <p>
    Хтось може сказати: «Ну що тут такого, якщо лише я проїду?» Але якщо по цій
    смузі проїде кожен «лише я», утворюється затор, у якому стоятиме весь
    громадський транспорт.
  </p>

  <p>
    Крім того, у такому заторі може затриматися швидка медична допомога або
    пожежна машина. І це особливо важливо в умовах постійних повітряних загроз.
  </p>

  <p>Тому я вважаю рух смугою громадського транспорту неприпустимим.</p>

  <p><strong>А якщо треба повернути праворуч?</strong></p>

  <p>
    Якщо потрібно повернути праворуч через смугу громадського транспорту,
    шукайте розрив у дорожній розмітці, призначений саме для перетину цієї смуги
    у потрібному напрямку.
  </p>

  <p>
    Важливо не помилитися з місцем повороту: перед перехрестям може бути ще один
    розрив, призначений для заїзду на прилеглу територію.
  </p>

  <p>
    Після виїзду з прилеглої території або після повороту праворуч на перехресті
    слід одразу залишити смугу громадського транспорту, перетнувши її у
    дозволеному місці.
  </p>

  <p>
    Короткотривала зупинка на таких смугах дозволяється лише для посадки або
    висадки пасажирів і лише за умови, що ви не створюєте перешкод громадському
    транспорту.
  </p>
</section>

