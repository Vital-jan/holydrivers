  <h2 class="section-title">📈 Ефект Даннінга—Крюгера</h2 class="section-title">

  <h2 class="section-title">Що це означає?</h2 class="section-title">

  <p>
    Це когнітивне упередження, за якого людина з недостатніми знаннями та
    навичками може переоцінювати власну компетентність.
  </p>

  <p>Простіше кажучи, це про те, що:</p>

  <p>
    <strong>
      Людина з мінімальними знаннями часто має завищену впевненість у собі.
    </strong>
  </p>

  <p>
    Коли знань мало — людині складно навіть оцінити, скільки вона ще не знає.
    Більшість ситуацій на дорозі, які стають типовими для досвідчених водіїв,
    початківцям ще невідомі. Ви не знаєте, як саме вчинити у разі несподіванки.
    Та скорше за все, оберете хибне рішення.
  </p>

  <h2 class="section-title">💡З мого досвіду:</h2 class="section-title">

  <p>
    Людина, яка має близько 20 годин водіння, дуже часто починає їздити не
    обережно, почуваючись за кермом надто впевнено.
  </p>

  <p>
    Але насправді цей досвід ще дуже невеликий. Існує безліч нетипових ситуацій,
    з якими ви ще не стикалися.
  </p>

  <p>
    Зі зростанням досвіду водій починає розуміти, що може відбутися за тих чи
    інших умов, і наперед знає, як не допустити небезпечної ситуації або швидко
    й безпечно знайти рішення.
  </p>
  <h2 class="section-title">📊 Що говорить статистика ДТП?</h2 class="section-title">

  <p>
    Недостатній досвід водіння — це не лише питання впевненості, а й цілком
    реальний ризик.
  </p>

  <p>
    За даними американського дослідження, ризик першої ДТП протягом першого
    місяця самостійного водіння був приблизно
    <strong>удвічі вищим</strong>, ніж у середньому протягом наступних
    одинадцяти місяців.
  </p>

  <p>
    Дослідження також свідчать, що ризик ДТП особливо високий у перші місяці
    після отримання посвідчення та поступово зменшується з набуттям досвіду.
  </p>

  <p>
    <strong>
      💡 Висновок простий: отримання посвідчення водія ще не означає набуття
      достатнього досвіду для безпечного керування в будь-яких дорожніх умовах.
    </strong>
  </p>
  <p>
    ⚖️ Саме тому підтримується такий прискіпливий контроль до водіїв-початківців
    - обмеження швидкості до 70 км/год перші два роки та перескладання іспиту у
    разі наявності 3 та більше порушень у цей період.
  </p>

  <h2 class="section-title">👩‍🏫 Порада автоінструктора</h2 class="section-title">

  <p>
    Починаючи самостійне водіння,
    <strong
      >опустіть свою «планку» значно нижче, ніж вам може здаватися.</strong
    >
  </p>

  <ul>
    <li>
      🚫 <strong>Не женіться за швидкістю</strong> — швидкість не дорівнює
      майстерності.
    </li>
    <li>‼️ Будьте обачливими та розсудливими на дорозі.</li>
    <li>🤍 І тоді водіння дійсно приноситиме вам спокій та задоволення.</li>
  </ul>
