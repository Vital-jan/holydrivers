      <ul>
        <li>вмикаємо поворотник</li>
        <li>знімаємо ручнік</li>
        <li>вмикаємо передачу</li>
      </ul>

      <p><strong>Вмикаємо передачу саме в останню чергу - це гарантує, що ми не зрушимо на ручніку.</strong></p>

      <ul>
        <li>дивимось в напрямку, звідки можемо очікувати перешкоду та переконуємось у безпеці (так, щоб інспектор помітив, що ми туди подивились)</li>
        <li>розпочинаємо рух</li>
        <li>робимо глибокий видих))) 😮‍💨</li>
      </ul>
    </li>

    <li>
      <p>На початку іспиту інспектор особливо уважно та прискіпливо дивиться на все. Тому зконцентруємось на дорожніх обставинах, знаках та розмітці замість "ой-ой-ой! щояроблюнетак??? цейдядькоменезавалить"))).</p>
    </li>

    <li>
      <p><strong>Найлютіші наші вороги на іспиті - стрес та поспіх.</strong> Від стресу ми позбавитись не зможемо. Кортизол так чи інакше вбризнеться у нашу кров та ми збережемо здатність робити лише те, чому навчені та можемо робити мимоволі. Але ж ми віримо в себе, чи не так? Ми знаємо, що навчені їздити. Цей дядько лише показує нам дорогу. А можна ще сказати собі "А я вже НЕ ЗДАВ!!!" Та після цього спокійно проїхати маршрут не "як на іспиті", а просто довезти цього дядька туди, куди він скаже)</p>
    </li>

    <li>
      <p><strong>⏳ Поспіх - наш ворог.</strong> Іспит триває НЕ МЕНШЕ 20 хвилин, вас про це попередять перед початком. І ось тут ключовий момент. Нам нема куди поспішати! Проїдемо маршрут бистріше - інспектор змушений буде придумати нам додаткове завдання - проїхати ще кружечок, зробити зупинку або припаркуватись.</p>

      <p>Якщо ж ми їдемо довго, не виключено, що маршрут нам вкоротять. Що траплялось не раз. Інспектор має право незначно змінювати маршрут в силу різних обставин.</p>

      <p>Зісно, не слід затягувати час навмисно. Зелене світло - ми стоїмо... нікого немає - ми стоїмо... Це виглядає, як невпевненість. Та ось коли є нагода когось пропустити там де слід, скористайтесь нагодою, замість думати, як бистріше проскочити. Не впевнені - не їдемо. Хай проїдуть усі, ми почекаємо. Стоячи на місці, помилку зробити важко)) Бібікають позаду? - Їхні проблеми. Нема мозгів - то хай бібікалка поламається. У нас іспит та нехай світ зачекає.</p>
    </li>

    <li>
      <p>Нас пропускають. Водій на головній чемним жестом руки нам показав нам "Проїжджайте будь ласка". По перше, інспектор міг не помітити жест водія, який нас пропустив. Буде зараховано помилку "Не переконались у безпеці маневру та не дали дорогу транспортному засобу, що рухався по головній".</p>

      <p><strong>Наші дії? Існує два варіанти.</strong></p>

      <p><strong>Перший:</strong> погодитись на пропозицію проїхати першим, але - промовити вголос "Нас пропускають, дякую" так, щоб інспектор це почув та камери теж це запишуть. Та показати тому водієві відповідний привітний жест рукою. По перше, це чемно з нашого боку. По друге, той водій зрозуміє, що ми прийняли його пропозицію та проїдемо першими. Якщо ми не надамо цей фідбек, другий водій, трохи почекавши, продовжить рух одночасно з нами і тоді точно нам зарахують помилку.</p>

      <p>І другий варіант - не скористатись пропозицією, показавши жестом руки "Проїжджайте". Можливо, так навіть надійніше. І додатковий час виграємо)</p>
    </li>

    <li>
      <p>Що відчуває інспектор, сідаючи біля нас у машину?</p>

      <p>Уявіть себе пасажиром таксі, коли ви знаєте, що таксист не має посвідчення водія, а лише десь хтось його чомусь навчив... Мдя.... Повірте, десь так саме почувається інспектор. За винятком того, що він має педаль гальм, якими скористається за першої нагоди, відчувши небезпеку.</p>

      <p>Інспектор не може залізти вам в голову, прочитати думки та здогадатись що ви зробите наступної миті. Повірте, це напружує.Та коли ви коментуєте ваші наміри вголос та завчасно, інспектор почувається значно спокійніше. А спокійний інспектор - гарний інспектор). Не питайте інспектора, чи можна коментувати. Ви маєте право щось собі бубоніти, скільки завгодно, це не заборонено.</p>

      <p>Якщо ж ви інтроверт та вичавити з вас слово складніше, ніж воду з каменю, що ж - покажіть ваші наміри невербально. Бачите перешкоду (припаркований автомобіль, наприклад) - увімкніть поворотник, подивіться у дзеркало, завчасно дотримайтесь безпечного інтервалу. Лише так інспектор зрозуміє, що ви збираєтесь цей автомобіль об'їхати. А коли стоїть автомобіль, ви їдете, не змінюючи напрямок та не подаючи жлдних ознак, що плануєте його об'їхати, ще й мовчите, як партизан - що залишається інспектору? - Правильно, нога мимоволі тягнеться до гальмівної педалі.</p>
    </li>

    <li>
      <p>Правий поворот. Здається, може бути простіше?</p>

      <p>Але ж ні. Дуже часто учні, повертаючи праворуч, лишають величезну порожнечу від краю дороги, в яку обов'язково хтось намагатиметься влізти. Повертаючи праворуч, притискайтесь до краю дороги. Але не так, щоб наїхати на бордюр заднім колесом)</p>

      <p>Припустимо, безпосередньо близько до перехрестя стоїть автомобіль. Об'їжджаючи його, ми вимушено опиняємось не в крайньому правому положенні. Об'їхавши автомобіль, поверніться у крайнє праве положення наскільки це можливо та розпочніть поворот.</p>

      <p>Після повороту бачите припаркований автомобіль. Все одно повертаємо в праву смугу. Зупиняємось. Бо усі, хто їдуть позаду, повернуть одразу у ліву смугу. Вмикаємо поворотніка, дивимось у дзеркало, спокійно відпочиваємо, доки проїдуть усі порушники. Час спливає.</p>
    </li>

    <li>
      <p>Зупинка. Інспектор може сказати "Зупиніть автомобіль у найближчому дозволеному місці". Це означає не припаркуватись, а саме зупинитись. Здавалось би, нема питань. А на цьому "сипляться" майже усі. Замість зупинятись, учні чогось продовжують рух. Проїхавши усі дозволені місця, зрештою зупиняються ближче 10 метрів до перехрестя або виїзду з прилеглої)</p>

      <p>Інспектор не має права провокувати нас на порушення. Тому й каже "у дозволеному місці". Ооо, так... Ми не дивились на знаки й тому не пам'ятаємо, чи був знак "зупинка заборонена"(((</p>

      <p>Ок, вважаємо, що знаку не було. Але чомусь у цьому місці жодної припаркованої машини... Це здається підозрілим та учні продовжують рух. А задача була зупинитись саме у НАЙБЛИЖЧОМУ дозволеному місці, а не за півкілометри.</p>

      <p><strong>Пам'ятайте: ніхто не припаркувався - не означає, що зупинку заборонено. Усі паркуються - не означає, що зупинку дозволено))</strong></p>

      <p>Тому дивіться не на інших, а на дорожні знаки та розмітку. Зліва від нас пунктирна лінія розмітки, заборонного знаку нема, бордюр жовтим не пофарбовано, зупинки транспорту за 30м нема, до перехрестя або виїзду з прилеглої більше 10 м - вмикаємо поворотника, дивимось у дзеркало, наближаємось до краю дороги, зупиняємось, затягуємо ручнік, вимикаємо поворотник. Глибокий видих, ми це змогли!) Та раптом голос інструктора: "- І по вашому тут є 10 метрів до виїзду з прилеглої?" Дивимось у дзеркало та мурашки по шкірі..... Хто знає, а може там дев'ять з половиною або з чвертиною... Ваша правильна відповідь, впевнено та чітко: "Так, звісно, тут більше 10 метрів. Якби було менше, я би тут не зупинила!")) - Цим ви показуєте інспекторові свої знання ПДР. З рулеткою ніхто міряти не бігатиме)</p>
    </li>

  </ol>

  <h2 class="section-title">⚠️ Типові помилки на іспиті</h2 class="section-title">

  <p>Типові помилки на іспиті можна перелічити на пальцях. Вони типові та їх повторюють більшість учнів. Ось вони:</p>

  <ul class="lesson-mistakes">
    <li>не увімкнули поворотник</li>
    <li>не зняли з ручніка,</li>
    <li>не подивились у напрямку небезпеки,</li>
    <li>запізно вимкнули поворотнік або зарано його увімкнули, вводячи в оману,</li>
    <li>перетнули суцільну лінію розмітки,</li>
    <li>не зупинились перед знаком Stop,</li>
    <li>розпочали правий поворот не з крайнього правого положення,</li>
    <li>закінчили правий поворот не в крайній правій смузі,</li>
    <li>повертаючи ліворуч, виїхали на зустрічну смугу,</li>
    <li>рухались лівою смугою, коли права вільна,</li>
    <li>не дотримались безпечного інтервалу під час об'їзду перешкоди,</li>
    <li>порушили правила зупинки.</li>
  </ul>

