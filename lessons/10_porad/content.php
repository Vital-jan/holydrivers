  <ol class="lesson-tips">

    <li>
      <p>Замість бігти з папірцем в руці скорше до біло-зеленої машинки, роздивіться, як вона стоїть. Чи не вивернуті колеса. Чи не стоїть поруч якась фішка (конус), яку можна зачіпити виїжджаючи). Промалюйте подумки траекторію виїзду (напрямок, передом чи задом, що може заважати та що чекає після виїзду з майданчика).</p>
    </li>

    <li>
      <p>Сівши у машину та пристібнувши ремінь, обов'язково перевірте статус автомобіля, адже ви ніколи не знаєте, у якому стані його залишив ваш попередник. Двигун може бути заглушений або вже заведений. Чи затягнений ручнік. Яка увімкнена передача (нейтральна, паркінг або інша).</p>

      <p>Запитавши інспектора "Де у вас тормоз, а де газ", можно поставити свій іспит під загрозу))) Але ви маєте повне право спитати - як зняти з ручніка, як налаштувати дзеркала, як увімкнути двірники або ближнє світло за потреби. Ці речі можуть відрізнятись у різних автомобілях, тому інспектор зобов'язаний вам це пояснити.</p>
