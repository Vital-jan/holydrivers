  <h2 class="section-title">
    🌧️ Аквапланування: чому швидкість має значення?
  </h2>

  <p>
    Уявіть, що ви повільно опускаєте долоню у воду. Вона легко
    занурюється, а вода плавно розходиться в різні боки.
  </p>

  <p>
    А тепер спробуйте різко вдарити долонею по поверхні води.
    Ви відчуєте досить сильний опір, хоча вода залишилася тією самою.
  </p>

  <p>
    <strong>
      Приблизно те саме відбувається з колесом автомобіля,
      коли воно потрапляє в калюжу.
    </strong>
  </p>

  <h2 class="section-title">🚗 На малій швидкості</h2>

  <p>
    Шина встигає витісняти воду з-під себе. Частина води
    відводиться канавками протектора, частина — в сторони.
    Колесо продовжує контактувати з асфальтом і зберігає
    зчеплення з дорогою.
  </p>

  <h2 class="section-title">⚠️ На великій швидкості</h2>

  <p>
    Колесо набігає на воду настільки швидко, що вона не встигає
    відводитися з-під шини. Перед колесом виникає підвищений
    тиск води, який починає піднімати шину над асфальтом.
  </p>

  <p>
    Це ефект, схожий на різкий удар долонею по воді:
    що швидший рух, то більший опір води.
  </p>

  <p>
    Коли швидкість надто велика, між шиною та дорогою
    утворюється водяний клин. Колесо частково або повністю
    втрачає контакт з асфальтом.
  </p>

  <p><strong>Це і є аквапланування.</strong></p>

