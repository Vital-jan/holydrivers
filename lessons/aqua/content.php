  <h2 class="section-title">⚠️ Чим небезпечне аквапланування?</h2>

  <p>
    Автомобіль може втратити здатність нормально повертати
    та гальмувати, навіть якщо водій правильно діє
    кермом і педалями.
  </p>

  <h2 class="section-title">🚦 Як зменшити ризик?</h2>

  <ul>
    <li>Зменшуйте швидкість на мокрій дорозі.</li>
    <li>Особливо зменшуйте швидкість перед калюжами.</li>
    <li>Уникайте різких поворотів керма та гальмувань.</li>
    <li>Стежте за станом протектора шин.</li>
    <li>Підтримуйте рекомендований тиск у шинах.</li>
    <li>За можливості об'їжджайте глибокі калюжі.</li>
  </ul>

  <p>
    <strong>Пам'ятайте:</strong> що вища швидкість,
    глибша вода та гірший стан протектора,
    то більший ризик аквапланування.
  </p>

  <p>
    <strong>
      Зменшуйте швидкість перед калюжами, а не тоді,
      коли вже втратили зчеплення з дорогою.
    </strong>
  </p>
  <p>
  До того ж, коли ми бачимо калюжу на дорозі, ми ніколи не знаємо,
  наскільки вона глибока. Вона може виявитися значно глибшою,
  ніж здається на перший погляд. А під водою може ховатися яма,
  потрапляння в яку навряд чи принесе щось приємне — ні водієві,
  ні автомобілю.
</p>

<p>
  І наостанок — мабуть, чи не кожен із нас хоча б раз у житті
  опинявся з ніг до голови облитим водою з-під коліс автомобіля,
  що промчав поруч.
  Водій поїхав далі в теплі та комфорті, можливо, навіть не помітивши,
  що залишив після себе вщент мокрих пішоходів.
  Тому дбаймо не лише про власну безпеку,
